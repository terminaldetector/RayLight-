"""Draw the 12 existing Abaddon meshes at their in-game visual scale."""
import argparse
import json
import math
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont


ROLES = (
    ("scanner_player", "Сканер игрока", "ОРИЕНТИР"),
    ("interceptor", "Перехватчик", "ЛЁГКИЙ"),
    ("mg", "Пикет", "ЛЁГКИЙ"),
    ("support", "Ремонтник", "ЛЁГКИЙ"),
    ("assault", "Штурмовик", "СРЕДНИЙ"),
    ("artillery", "Артиллерия", "СРЕДНИЙ"),
    ("grav", "Грависборщик", "СРЕДНИЙ"),
    ("heavy", "Осадная мортира", "ТЯЖЁЛЫЙ"),
    ("rocket_strider", "Ракетный носитель", "ТЯЖЁЛЫЙ"),
    ("plasma_strider", "Плазменный носитель", "ТЯЖЁЛЫЙ"),
    ("heavy_elite", "Бронедрон", "БОСС"),
    ("arc_elite", "Дуговой штурмовик", "БОСС"),
)
PIXELS_PER_UNIT = 0.82


def dot(a, b):
    return sum(x * y for x, y in zip(a, b))


def unit(vector):
    length = math.sqrt(dot(vector, vector))
    return tuple(c / length for c in vector)


def font(weight, size):
    filename = "DejaVuSans-Bold.ttf" if weight == "bold" else "DejaVuSans.ttf"
    return ImageFont.truetype(filename, size)


def draw_asset(draw, data, role, center):
    id_, _, _ = role
    # The authored player mesh is drawn at 1, independent of scanner native model scale.
    spec = dict(data["scanner"], scale=1, color=(111, 195, 216)) if id_ == "scanner_player" else data["drones"][id_]
    factor = spec["scale"]
    toward = unit((3.5, -4.25, 2.9))
    right = unit((-toward[1], toward[0], 0))
    up = (
        -toward[2] * right[1],
        toward[2] * right[0],
        toward[0] * right[1] - toward[1] * right[0],
    )
    light = unit((1.6, -0.7, 2.8))
    triangles, min_bound, max_bound = [], [math.inf] * 3, [-math.inf] * 3
    for material, faces in sorted(data["models"][spec["mesh"]].items()):
        base = spec["color"] if material == "emit" else data["palette"][material]
        for face in faces:
            vertices, normal = face[:3], face[3]
            for vertex in vertices:
                for axis in range(3):
                    min_bound[axis] = min(min_bound[axis], vertex[axis])
                    max_bound[axis] = max(max_bound[axis], vertex[axis])
            if dot(normal, toward) <= 0:
                continue
            strength = 1.17 if material in {"emit", "siege_eye", "lamp", "hot"} else 0.62 + 0.61 * max(0, dot(normal, light))
            color = tuple(min(255, int(value * strength)) for value in base)
            points = [(dot(vertex, right), -dot(vertex, up)) for vertex in vertices]
            triangles.append((sum(dot(vertex, toward) for vertex in vertices), points, color))
    mid = [(low + high) / 2 for low, high in zip(min_bound, max_bound)]
    mid_x, mid_y = dot(mid, right), -dot(mid, up)
    step = factor * PIXELS_PER_UNIT
    for _, points, color in sorted(triangles, key=lambda item: item[0]):
        draw.polygon(
            [(round(center[0] + (x - mid_x) * step), round(center[1] + (y - mid_y) * step)) for x, y in points],
            fill=color,
        )
    return factor * max(high - low for low, high in zip(min_bound, max_bound))


def draw_comparison(data):
    image = Image.new("RGB", (1800, 1180), "#131c21")
    draw = ImageDraw.Draw(image)
    ink, muted, accent = "#e7f2f0", "#b4c4c5", "#9edbcd"
    draw.text((31, 26), "Half-Life: Abaddon", ink, font("bold", 30))
    draw.text((32, 69), "Контроль силуэтов · текущие игровые сетки и масштаб", muted, font("normal", 20))
    draw.line((1610, 61, 1692, 61), fill=accent, width=2)
    for x in (1610, 1692):
        draw.line((x, 55, x, 67), fill=accent, width=2)
    draw.text((1610, 75), "100 Source units", muted, font("normal", 16))
    for index, role in enumerate(ROLES):
        id_, title, size_class = role
        x, y = 31 + (index % 4) * 437, 108 + (index // 4) * 353
        draw.rectangle((x, y, x + 425, y + 340), "#19262c", outline="#34484c")
        draw.text((x + 16, y + 13), size_class, accent, font("bold", 14))
        draw.text((x + 16, y + 36), title, ink, font("bold", 18))
        diameter = draw_asset(draw, data, role, (x + 212, y + 185))
        draw.text((x + 16, y + 310), id_, muted, font("normal", 16))
        draw.text((x + 407, y + 310), f"{diameter:.1f} SU", ink, font("normal", 16), anchor="ra")
    return image


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("geometry", type=Path, help="JSON generated by tests/export_art.lua")
    parser.add_argument("output", type=Path, help="Target PNG")
    args = parser.parse_args()
    draw_comparison(json.loads(args.geometry.read_text())).save(args.output)


if __name__ == "__main__":
    main()
